CREATE OR REPLACE FUNCTION public.refresh_menu_item_availability (
  p_menu_item_id bigint
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  has_recipe boolean;
  ingredients_available boolean;
begin
  select exists (
    select 1 from public.menu_item_ingredients where menu_item_id = p_menu_item_id
  ) into has_recipe;

  if not has_recipe then
    update public.menu_items set is_available = false where id = p_menu_item_id;
    return;
  end if;

  select not exists (
    select 1
    from public.menu_item_ingredients mi
    join public.ingredients i on i.id = mi.ingredient_id
    where mi.menu_item_id = p_menu_item_id and i.current_stock < mi.quantity
  ) into ingredients_available;

  update public.menu_items set is_available = ingredients_available where id = p_menu_item_id;
end;
$function$;

