CREATE OR REPLACE FUNCTION public.get_customer_menu()
  RETURNS TABLE (
    id            bigint,
    name          text,
    description   text,
    brand         text,
    main_category text,
    sub_category  text,
    price         numeric,
    image_url     text,
    available     integer,
    is_available  boolean,
    is_featured   boolean,
    variants      jsonb
  )
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select
    m.id,
    m.name,
    m.description,
    m.brand,
    main_category.name,
    sub_category.name,
    m.price,
    m.image_url,
    case when coalesce(stock.has_recipe, false) and m.is_available
      then coalesce(stock.portions, 0) else 0 end::integer,
    coalesce(stock.has_recipe, false) and m.is_available and coalesce(stock.portions, 0) > 0,
    m.is_featured,
    coalesce(variants.items, '[]'::jsonb)
  from public.menu_items m
  left join public.menu_categories main_category on main_category.id = m.category_id
  left join public.menu_categories sub_category on sub_category.id = m.subcategory_id
  left join lateral (
    select
      count(*) > 0 as has_recipe,
      floor(min(i.current_stock / mi.quantity))::integer as portions
    from public.menu_item_ingredients mi
    join public.ingredients i on i.id = mi.ingredient_id
    where mi.menu_item_id = m.id
  ) stock on true
  left join lateral (
    select jsonb_agg(jsonb_build_object(
      'id', v.id,
      'variant_key', v.variant_key,
      'name', v.name,
      'price', v.price
    ) order by v.sort_order, v.id) as items
    from public.menu_item_variants v
    where v.menu_item_id = m.id
  ) variants on true
  where m.is_active
  order by m.id;
$function$;

