CREATE OR REPLACE FUNCTION public.cancel_customer_order (
  p_qr_token     text,
  p_order_number text
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
DECLARE
  v_order public.orders;
BEGIN
  IF NOT public.is_valid_qr_token(p_qr_token) THEN
    RAISE EXCEPTION 'Invalid or expired QR access';
  END IF;

  UPDATE public.orders
  SET status = 'Cancelled'
  WHERE order_number = p_order_number
    AND source = 'QR Order'
    AND status = 'Pending'
  RETURNING * INTO v_order;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Only pending customer orders can be cancelled';
  END IF;

  RETURN jsonb_build_object(
    'orderNumber', v_order.order_number,
    'status', v_order.status
  );
END;
$function$;

REVOKE ALL ON FUNCTION "public"."cancel_customer_order"(text, text) FROM "service_role";

CREATE OR REPLACE FUNCTION public.create_customer_order (
  p_qr_token      text,
  p_customer_name text,
  p_order_type    public.order_type,
  p_notes         text,
  p_items         jsonb
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_order public.orders;
  v_item jsonb;
  v_menu public.menu_items;
  v_variant public.menu_item_variants;
  v_variant_key text;
  v_price numeric(10,2);
  v_items jsonb := '[]'::jsonb;
  v_total numeric(12,2) := 0;
  v_qty integer;
begin
  if not public.is_valid_qr_token(p_qr_token) then
    raise exception 'Invalid or expired QR access';
  end if;

  if nullif(trim(p_customer_name), '') is null then
    raise exception 'Customer name is required';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'At least one item is required';
  end if;

  insert into public.orders(customer_name, order_type, source, notes)
    values(trim(p_customer_name), p_order_type, 'QR Order', coalesce(p_notes, ''))
    returning * into v_order;

  for v_item in select value from jsonb_array_elements(p_items) loop
    select * into v_menu
    from public.menu_items
    where id = (v_item->>'menuItemId')::bigint
      and is_active
      and is_available;

    if not found then
      raise exception 'A menu item is unavailable';
    end if;

    v_variant_key := nullif(v_item->>'selectedVariantId', '');

    if v_variant_key is null then
      v_price := v_menu.price;
    else
      select * into v_variant
      from public.menu_item_variants
      where menu_item_id = v_menu.id
        and variant_key = v_variant_key;

      if not found then
        raise exception 'A menu variant is unavailable';
      end if;

      v_price := v_variant.price;
    end if;

    v_qty := (v_item->>'quantity')::integer;

    if v_price is null or v_qty < 1 or v_qty > 99 then
      raise exception 'Invalid item price or quantity';
    end if;

    insert into public.order_items(
      order_id,
      menu_item_id,
      item_name,
      selected_variant_key,
      variant_label,
      unit_price,
      quantity,
      recommendation_source
    )
    values(
      v_order.id,
      v_menu.id,
      v_menu.name,
      v_variant_key,
      case when v_variant_key is null then null else v_variant.name end,
      v_price,
      v_qty,
      nullif(v_item->>'recommendationSource', '')
    );

    v_total := v_total + v_price * v_qty;

    v_items := v_items || jsonb_build_array(
      jsonb_build_object(
        'menuItemId', v_menu.id,
        'name', v_menu.name,
        'selectedVariantId', v_variant_key,
        'variantLabel', case when v_variant_key is null then null else v_variant.name end,
        'price', v_price,
        'quantity', v_qty,
        'subtotal', v_price * v_qty,
        'recommendationSource', nullif(v_item->>'recommendationSource', '')
      )
    );
  end loop;

  return jsonb_build_object(
    'id', v_order.id,
    'orderNumber', v_order.order_number,
    'customerName', v_order.customer_name,
    'orderType', v_order.order_type,
    'status', v_order.status,
    'notes', v_order.notes,
    'items', v_items,
    'totalAmount', v_total,
    'createdAt', v_order.created_at
  );
end;
$function$;

REVOKE ALL ON FUNCTION "public"."create_customer_order"(text, text, public.order_type, text, jsonb) FROM "service_role";

