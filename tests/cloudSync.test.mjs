async function fixture({legacy=false}={}) {
  // Initialize sequentially to avoid two simultaneous WASM/database unpacking
  // spikes on machines with limited memory. SQL behavior remains unchanged.
  const options={postgresqlconf:"shared_buffers=8MB\nwork_mem=1MB\nmaintenance_work_mem=4MB\n"};
  const local = await PGlite.create(options);
  let remote;
  try {
  remote = await PGlite.create(options);
  for (const db of [local,remote]) {
    await db.exec(base);
    const fn = oldMirror.match(/create or replace function public\.deduct_order_ingredients_on_completion\(\)[\s\S]*?\$\$;/i)[0];
    await db.exec(fn);
    await db.exec("create trigger deduct after update of status on orders for each row execute function deduct_order_ingredients_on_completion()");
    await db.exec(receiver);
  }
  await local.exec(`
    insert into menu_categories values(1,'Food',null,'2026-01-01');
    insert into ingredients values(1,'Rice',100,10,'Grams',0.05,'2026-01-01');
    insert into menu_items values(1,'Meal',1,'2026-01-01');
    insert into menu_item_ingredients values(1,1,2);
    insert into orders values(1,'DY-1','Pending',null,'2026-01-01');
    insert into order_items(id,order_id,menu_item_id,quantity,unit_price) values(1,1,1,2,50);
    insert into stock_movements values(1,1,-4,'Order OLD completed',null,'2026-01-01');
  `);
  if(legacy){
    await local.exec(legacyLocal.split(/\r?\ndo \$\$/)[0]);
    await local.exec("insert into local_sync.outbox(table_name,operation,row_data) select 'ingredients','UPDATE',to_jsonb(i)||'{\"current_stock\":50}' from ingredients i;insert into local_sync.outbox(table_name,operation,row_data) values('ingredients','DELETE','{\"id\":99}')");
  }
  await local.exec(localSetup);
  await local.exec("update local_sync.settings set sync_window_seconds=null");
  await local.exec("update local_sync.worker_status set configured=true,heartbeat_at=clock_timestamp();set test.app_role='SUPER_ADMIN'");
  const pool = { query: (...args)=>local.query(...args), connect: async()=>({query:(...args)=>local.query(...args),release(){}}) };
  const cloud = { async rpc(name,args) {
    assert.equal(name,"apply_cloud_sync_batch");
    try {return {data:(await remote.query("select public.apply_cloud_sync_batch($1,$2,$3) as result",[args.p_source_id,args.p_batch_id,args.p_events_json])).rows[0].result,error:null};}
    catch(error){return {data:null,error};}
  } };
  return {local,remote,pool,cloud,run:()=>processSyncRun({pool,cloud,automatic:true}),close:()=>Promise.all([local.close(),remote.close()])};
  } catch(error) {await Promise.allSettled([local.close(),remote?.close()]);throw error;}
}

test("an unversioned variant conflict returns PT409 once, retains the batch and succeeds after explicit reconciliation",async()=>{
  const f=await fixture();
  try {
    await f.run();
    await f.local.exec("insert into menu_item_variants values(14,1,'16 oz',75,1,'16oz')");
    await f.remote.exec("insert into menu_item_variants values(14,1,'16 oz',75,0,'16oz')");
    const before=(await f.local.query("select last_successful_sync_at from local_sync.settings")).rows[0].last_successful_sync_at;
    let calls=0;
    const cloud={rpc:async(...args)=>{calls++;const result=await f.cloud.rpc(...args);assert.equal(result.error.code,'PT409');return result;}};
    const failed=await processSyncRun({pool:f.pool,cloud,automatic:true});
    assert.equal(calls,1);assert.equal(failed.status,'failed');
    assert.match(failed.error,/unversioned data.*PT409.*for review/);
    assert.equal((await f.remote.query("select sort_order from menu_item_variants where id=14")).rows[0].sort_order,0);
    assert.deepEqual((await f.local.query("select last_successful_sync_at from local_sync.settings")).rows[0].last_successful_sync_at,before);
    const batch=(await f.local.query("select id,payload::text from local_sync.batches where confirmed_at is null and superseded_at is null")).rows[0];
    assert.equal((await f.remote.query("select count(*) from cloud_sync.receipts where batch_id=$1",[batch.id])).rows[0].count,0);
    await f.remote.exec("update menu_item_variants set sort_order=1 where id=14");
    const fixed=await f.run();assert.equal(fixed.status,'succeeded');assert.equal(fixed.synced_count,1);
    assert.equal((await f.remote.query("select count(*) from menu_item_variants where id=14")).rows[0].count,1);
    assert.deepEqual((await f.local.query("select payload::text from local_sync.batches where id=$1",[batch.id])).rows[0].payload,batch.payload);
    assert.ok((await f.local.query("select last_successful_sync_at from local_sync.settings")).rows[0].last_successful_sync_at>=before);
    const correction=await readFile(new URL("../supabase/migrations/20261031000000_sync_conflict_http_errors.sql",import.meta.url),'utf8');
    await f.remote.exec(correction);
    const definition=(await f.remote.query("select pg_get_functiondef('public.apply_cloud_sync_batch(uuid,uuid,text)'::regprocedure) as definition")).rows[0].definition;
    assert.equal((definition.match(/errcode='PT409'/g)||[]).length,5);
    assert.doesNotMatch(definition,/errcode='40001'/);
    assert.match(definition,/statement_timeout.*90s/);
  } finally {await f.close();}
});

