-- Reusable menu variant sets.
--
-- Items with the same options and prices can reference one variant set instead
-- of storing a duplicate 12 oz / 16 oz row for every item. Items with different
-- prices should reference a different set.
--
-- This is a schema draft only. Migrate get_customer_menu and the order-creation
-- RPCs to read through these tables before moving or deleting existing rows in
-- menu_item_variants.

CREATE TABLE IF NOT EXISTS public.menu_variant_sets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.menu_variant_options (
  variant_set_id bigint NOT NULL
    REFERENCES public.menu_variant_sets(id) ON DELETE CASCADE,
  variant_key text NOT NULL,
  name text NOT NULL,
  price numeric(10, 2) NOT NULL CHECK (price >= 0),
  sort_order integer NOT NULL DEFAULT 0,
  PRIMARY KEY (variant_set_id, variant_key)
);

-- One link per item. Many items can share the same variant set.
CREATE TABLE IF NOT EXISTS public.menu_item_variant_sets (
  menu_item_id bigint PRIMARY KEY
    REFERENCES public.menu_items(id) ON DELETE CASCADE,
  variant_set_id bigint NOT NULL
    REFERENCES public.menu_variant_sets(id) ON DELETE RESTRICT
);

ALTER TABLE public.menu_variant_sets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.menu_variant_options ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.menu_item_variant_sets ENABLE ROW LEVEL SECURITY;

-- Example shared set for Iced Drip Coffee and any other items with the same
-- sizes and prices. Run the item-link statement once per item that should use it.
INSERT INTO public.menu_variant_sets (name)
VALUES ('12 oz / 16 oz - ₱65 / ₱75')
ON CONFLICT (name) DO NOTHING;

INSERT INTO public.menu_variant_options
  (variant_set_id, variant_key, name, price, sort_order)
SELECT variant_set.id, option.variant_key, option.name, option.price, option.sort_order
FROM public.menu_variant_sets AS variant_set
CROSS JOIN (VALUES
  ('12oz', '12 oz', 65.00::numeric, 0),
  ('16oz', '16 oz', 75.00::numeric, 1)
) AS option(variant_key, name, price, sort_order)
WHERE variant_set.name = '12 oz / 16 oz - ₱65 / ₱75'
ON CONFLICT (variant_set_id, variant_key) DO UPDATE
SET name = EXCLUDED.name,
    price = EXCLUDED.price,
    sort_order = EXCLUDED.sort_order;

-- Example: link Iced Drip Coffee (menu item id 31) to the reusable size set.
-- Repeat for other items that use these exact sizes and prices.
INSERT INTO public.menu_item_variant_sets (menu_item_id, variant_set_id)
SELECT 31, variant_set.id
FROM public.menu_variant_sets AS variant_set
WHERE variant_set.name = '12 oz / 16 oz - ₱65 / ₱75'
ON CONFLICT (menu_item_id) DO UPDATE
SET variant_set_id = EXCLUDED.variant_set_id;
